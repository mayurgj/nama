#!/usr/bin/env python3
"""Bundle each provider into one self-contained file under providers/.

Nuvio loads one plain JS file per provider, so the shared modules are concatenated
ahead of the provider's own code. No Node/esbuild needed.

    NAMA_TMDB_KEY=xxxx python3 build.py            # all providers
    NAMA_TMDB_KEY=xxxx python3 build.py animesalt  # one provider
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
COMMON = ["http.js", "tmdb.js", "format.js", "fireplayer.js", "toro.js"]
PLACEHOLDER = "PUT_YOUR_TMDB_API_KEY_HERE"
FOOTER = """
if (typeof module !== "undefined" && module.exports) {
  module.exports = { getStreams: getStreams };
} else {
  global.getStreams = getStreams;
}
"""


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as f:
        return f.read()


def build(provider, version):
    parts = ["// NAMA %s provider v%s, generated by build.py; edit src/ instead.\n" % (provider, version)]
    for name in COMMON:
        parts.append("// ---- common/%s ----\n%s" % (name, read("src", "common", name)))
    parts.append("// ---- %s/index.js ----\n%s" % (provider, read("src", provider, "index.js")))
    code = "\n".join(parts) + FOOTER
    key = os.environ.get("NAMA_TMDB_KEY", "").strip()
    if key:
        code = code.replace(PLACEHOLDER, key)
    else:
        print("warning: NAMA_TMDB_KEY not set, %s bundle has no TMDB key" % provider)
    out = os.path.join(ROOT, "providers", provider + ".js")
    with open(out, "w", encoding="utf-8") as f:
        f.write(code)
    print("built providers/%s.js (%d bytes)" % (provider, len(code)))


def main():
    manifest = json.loads(read("manifest.json"))
    wanted = sys.argv[1:]
    for entry in manifest["scrapers"]:
        if not wanted or entry["id"] in wanted:
            build(entry["id"], entry["version"])


if __name__ == "__main__":
    main()
